"""Regenerate utils/festiveGreetingRaster.js (1-bit ESC/POS raster of the
seasonal receipt greeting).

The greeting is printed as a bitmap so that the star, the French accents
(Ë, É) and the "œ" ligature print identically on every ESC/POS printer,
whatever character code page it is configured for.

Usage:  python3 scripts/build_festive_raster.py [--png preview.png]
Needs Pillow and the DejaVu fonts (fonts-dejavu-core).
"""
import base64, sys, unicodedata
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

WIDTH = 512            # dots; fits the 72mm (576-dot) and 64mm (512-dot) print heads of 80mm printers
MARGIN = 8
FONT_DIR = Path("/usr/share/fonts/truetype/dejavu")
BOLD = FONT_DIR / "DejaVuSans-Bold.ttf"

LINES = {
    "title": "★ JOYEUX NOËL ★",
    "subtitle": "ET BONNE ANNÉE !",
    "wishes": "Nos meilleurs vœux",
    "year": "2027",
    "message": "Que cette nouvelle année vous apporte joie, santé et prospérité !",
}

def font(size):
    return ImageFont.truetype(str(BOLD), size)

def wrap(draw, text, fnt, max_width):
    words, lines, line = text.split(), [], ""
    for word in words:
        candidate = f"{line} {word}".strip()
        if draw.textlength(candidate, font=fnt) <= max_width:
            line = candidate
        else:
            lines.append(line)
            line = word
    lines.append(line)
    return lines

def render():
    img = Image.new("1", (WIDTH, 600), 1)
    d = ImageDraw.Draw(img)
    y = 4

    def dashed(y):
        x = MARGIN
        while x < WIDTH - MARGIN:
            d.line([(x, y), (min(x + 10, WIDTH - MARGIN), y)], fill=0, width=2)
            x += 18
        return y + 2

    def centered(text, fnt, y, gap):
        text = unicodedata.normalize("NFC", text)
        w = d.textlength(text, font=fnt)
        box = fnt.getbbox(text)
        d.text(((WIDTH - w) / 2, y - box[1] + 0), text, font=fnt, fill=0)
        return y + (box[3] - box[1]) + gap

    y = dashed(y) + 14
    y = centered(LINES["title"], font(30), y, 10)
    y = centered(LINES["subtitle"], font(26), y, 18)
    d.line([((WIDTH - 190) / 2, y), ((WIDTH + 190) / 2, y)], fill=0, width=2)
    y += 16
    y = centered(LINES["wishes"], font(23), y, 10)
    y = centered(LINES["year"], font(64), y, 14)
    msg_font = font(21)
    for line in wrap(d, LINES["message"], msg_font, WIDTH - 2 * MARGIN - 24):
        y = centered(line, msg_font, y, 7)
    y += 8
    y = dashed(y) + 2
    return img.crop((0, 0, WIDTH, y))

def pack(img):
    # ESC/POS raster bytes: 1 = black dot, MSB first, rows top to bottom.
    w, h = img.size
    row_bytes = w // 8
    out = bytearray()
    px = img.load()
    for yy in range(h):
        for xb in range(row_bytes):
            byte = 0
            for bit in range(8):
                if px[xb * 8 + bit, yy] == 0:
                    byte |= 0x80 >> bit
            out.append(byte)
    return row_bytes, h, bytes(out)

def main():
    img = render()
    row_bytes, height, data = pack(img)
    if "--png" in sys.argv:
        img.save(sys.argv[sys.argv.index("--png") + 1])
    target = Path(__file__).resolve().parent.parent / "utils" / "festiveGreetingRaster.js"
    b64 = base64.b64encode(data).decode()
    chunks = "\n".join(f'  "{b64[i:i + 100]}" +' for i in range(0, len(b64), 100)).rstrip(" +")
    target.write_text(
        "// Generated by scripts/build_festive_raster.py. Do not edit by hand.\n"
        "// 1-bit ESC/POS raster of the seasonal receipt greeting (see utils/festiveGreeting.js).\n"
        "module.exports = {\n"
        f"  widthBytes: {row_bytes},\n"
        f"  height: {height},\n"
        "  data:\n"
        f"{chunks},\n"
        "};\n",
        encoding="utf-8",
    )
    print(f"wrote {target} ({row_bytes * 8}x{height} dots, {len(data)} bytes)")

if __name__ == "__main__":
    main()
